// Helper function to get optimized image URL with parameters
export function getOptimizedImageUrl(
  url: string,
  options: {
    width?: number;
    height?: number;
    quality?: number;
    fit?: 'crop' | 'contain' | 'cover' | 'fill';
    format?: 'auto' | 'webp' | 'avif';
  } = {}
): string {
  const { width, height, quality = 85, fit = 'crop', format = 'auto' } = options;

  // If it's an Unsplash URL, add query parameters
  if (url.includes('unsplash.com')) {
    const params = new URLSearchParams();
    if (width) params.set('w', width.toString());
    if (height) params.set('h', height.toString());
    params.set('q', quality.toString());
    params.set('fit', fit);
    params.set('auto', format);
    params.set('fm', format === 'auto' ? 'webp' : format);

    return `${url.split('?')[0]}?${params.toString()}`;
  }

  return url;
}

